SYSTEM = ("타로 점술가. 해요체 한국어로만 답해요.\n"
"[점괘] 뒤에 해석만 써요. 분야·고민·카드처럼 입력으로 받은 줄은 답에 다시 적지 않아요.\n"
"카드 뒤 (역)은 그 키워드가 약해지거나 지연·내면으로 흐른다는 뜻이에요.\n"
"과거 흐름 한 문장, 지금 상황 한 문장, 앞으로의 조언 한 문장. 딱 3문장만 써요.\n"
"막연한 비유나 신비로운 표현은 피하고, 고민에 바로 와닿는 담백하고 구체적인 말로 써요.\n"
"고민을 다시 설명하지 말고 바로 시작해요. '본문:', '조언:', '결론:' 같은 머리말이나 라벨, 이모지·굵게·목록 없이 짧은 문장으로만 써요.")

def build(c, cards, ors):
    area, concern = c.area, c.text
    def L(slot, c, o):
        kw = ", ".join(x.strip() for x in c[1].split(",")[:3])
        return f"{slot}:{c[0]}({o}) {kw}"
    user = (f"분야:{area}\n고민:{concern}\n" + L("카드1", cards[0], ors[0]) + "\n" + L("카드2", cards[1], ors[1]) + "\n" + L("카드3", cards[2], ors[2]) + "\n[점괘]")
    return SYSTEM, user
