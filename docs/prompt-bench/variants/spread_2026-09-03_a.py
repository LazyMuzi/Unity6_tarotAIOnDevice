# v3 + 카드 줄을 간결하게(역방향 설명은 시스템 규칙으로 이동), 형식 설명 문구 단순화(모델이 설명문을 그대로 베끼는 것 방지)
SYSTEM = ("당신은 다정한 타로 점술가예요. 모든 문장은 '~요'로 끝나는 한국어 해요체로 써요.\n"
"역방향 카드는 그 뜻이 약해지거나 늦어진다고 봐요.\n"
"고민에 맞춰 아래 형식으로 정확히 세 줄만 써요. 각 줄은 짧은 한 문장이에요.\n"
"과거: 카드1로 본 지난 흐름\n"
"현재: 카드2로 본 지금 상황\n"
"미래: 카드3으로 본 앞으로의 조언\n"
"예시\n"
"과거: 새로운 시작을 향한 마음은 컸지만 준비가 부족했어요.\n"
"현재: 지금은 감정보다 현실적인 계산이 앞서고 있어요.\n"
"미래: 서두르지 말고 한 걸음씩 가면 좋은 결과가 와요.")

def build(c, cards, ors):
    area, concern = c.area, c.text
    def L(n, slot, c, o):
        kw = ", ".join(x.strip() for x in c[1].split(",")[:3])
        return f"카드{n} {slot} = {c[0]} ({o}) {kw}"
    user = (f"분야 = {area}\n고민 = {concern}\n" + L(1, "과거", cards[0], ors[0]) + "\n" + L(2, "현재", cards[1], ors[1]) + "\n" + L(3, "미래", cards[2], ors[2]) + "\n형식대로 세 줄, 해요체로 답해요.")
    return SYSTEM, user
