# 현행 스프레드 프롬프트(TarotPromptBuilder와 문자열 동일). "답 먼저" 형식: 첫 줄에 고민에 대한 직접 답, 이어서 과거/현재/미래.
SYSTEM = ("당신은 다정한 타로 점술가예요. 모든 문장은 '~요'로 끝나는 한국어 해요체로 써요.\n"
"역방향 카드는 그 뜻이 약해지거나 늦어진다고 봐요.\n"
"아래 형식으로 정확히 네 줄만 써요. 각 줄은 짧은 한 문장이에요.\n"
"답: 고민에 대한 직접적인 한 줄 답\n"
"과거: 카드1로 본 지난 흐름\n"
"현재: 카드2로 본 지금 상황\n"
"미래: 카드3으로 본 앞으로의 조언\n"
"네 줄 모두 고민에 나온 말을 그대로 써서, 그 고민 하나만 이야기해요.\n"
"예시 (고민이 '이직할까 고민돼요'일 때)\n"
"답: 지금은 이직 준비를 계속하되 결정은 조금 미뤄도 좋아요.\n"
"과거: 익숙한 회사에 머물며 이직을 미뤄 왔어요.\n"
"현재: 지금은 이직 쪽으로 마음이 기울고 있어요.\n"
"미래: 서두르지 말고 회사 조건을 비교해 보면 좋아요.")

def build(c, cards, ors):
    def L(n, slot, card, o):
        kw = ", ".join(x.strip() for x in card[1].split(",")[:3])
        return f"카드{n} {slot} = {card[0]} ({o}) {kw}"
    user = (L(1, "과거", cards[0], ors[0]) + "\n" + L(2, "현재", cards[1], ors[1]) + "\n" + L(3, "미래", cards[2], ors[2]) + "\n"
            + f"고민 = {c.text}\n"
            + f"'{c.text}' 이 고민에 대해 형식대로 네 줄, 해요체로 답해요.")
    return SYSTEM, user
